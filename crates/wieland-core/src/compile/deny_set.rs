use std::collections::HashSet;
use std::path::PathBuf;

use super::{Artifact, CompileError, in_pack, ordered, pack_language};
use crate::corpus::Corpus;
use crate::frontmatter::section_body;
use crate::rule::{Enforceability, Language, Rule, Severity};

pub struct DenyLint {
    pub lint: String,
    pub rule_id: String,
    pub title: String,
    pub statement: String,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Level {
    Error,
    Warn,
}

impl Level {
    pub fn name(self) -> &'static str {
        match self {
            Level::Error => "error",
            Level::Warn => "warn",
        }
    }
}

#[derive(Debug, Clone)]
pub struct Detector {
    pub name: String,
    pub level: Level,
    pub rule_id: String,
    pub title: String,
    pub statement: String,
}

pub const OXLINT_CATEGORIES: [&str; 7] = [
    "correctness",
    "nursery",
    "pedantic",
    "perf",
    "restriction",
    "style",
    "suspicious",
];

pub fn deny_set(corpus: &Corpus) -> Vec<DenyLint> {
    let mut out = Vec::new();
    let mut seen = HashSet::new();
    for rule in ordered(corpus) {
        if rule.severity != Severity::Deny || rule.enforceability != Enforceability::Gate {
            continue;
        }
        for lint in &rule.detect.clippy {
            if seen.insert(lint.clone()) {
                out.push(DenyLint {
                    lint: lint.clone(),
                    rule_id: rule.id.clone(),
                    title: rule.title.clone(),
                    statement: section_body(&rule.body, "Rule").unwrap_or_default(),
                });
            }
        }
    }
    out
}

fn level_of(rule: &Rule) -> Level {
    if rule.severity == Severity::Deny && rule.enforceability == Enforceability::Gate {
        Level::Error
    } else {
        Level::Warn
    }
}

fn detectors(corpus: &Corpus, pick: impl Fn(&Rule) -> &Vec<String>) -> Vec<Detector> {
    let mut out: Vec<Detector> = Vec::new();
    let mut seen = HashSet::new();
    for rule in ordered(corpus) {
        for name in pick(rule) {
            if seen.insert(name.clone()) {
                out.push(Detector {
                    name: name.clone(),
                    level: level_of(rule),
                    rule_id: rule.id.clone(),
                    title: rule.title.clone(),
                    statement: section_body(&rule.body, "Rule").unwrap_or_default(),
                });
            }
        }
    }
    out.sort_by(|a, b| a.name.cmp(&b.name));
    out
}

pub fn oxlint_rules(corpus: &Corpus) -> Vec<Detector> {
    detectors(corpus, |r| &r.detect.oxlint)
}

pub fn tsconfig_flags(corpus: &Corpus) -> Vec<Detector> {
    detectors(corpus, |r| &r.detect.tsconfig)
}

pub fn golangci_linters(corpus: &Corpus) -> Vec<Detector> {
    detectors(corpus, |r| &r.detect.golangci)
}

pub fn render(corpus: &Corpus, sha: &str) -> Result<Vec<Artifact>, CompileError> {
    match pack_language(corpus) {
        Language::Rust => render_rust(corpus, sha),
        Language::Typescript => Ok(render_typescript(corpus, sha)),
        Language::Go => Ok(render_go(corpus, sha)),
    }
}

fn render_rust(corpus: &Corpus, sha: &str) -> Result<Vec<Artifact>, CompileError> {
    let lints = deny_set(corpus);

    let mut table = format!("# wieland-corpus: {sha}\n");
    table.push_str("# Generated by `wieland compile deny-set`. Paste into Cargo.toml.\n");
    table.push_str("[lints.clippy]\n");
    for entry in &lints {
        table.push_str(&format!("{} = \"deny\"\n", entry.lint));
    }

    let mut config = format!("# wieland-corpus: {sha}\n");
    config.push_str("# clippy configuration. Lint LEVELS live in lints.toml ([lints.clippy]).\n");
    config.push_str("# The current deny-set needs no per-lint configuration.\n");

    let mut map = format!("# wieland-corpus: {sha}\n");
    map.push_str("# clippy_lint\trule_id\ttitle\n");
    for entry in &lints {
        map.push_str(&format!(
            "clippy::{}\t{}\t{}\n",
            entry.lint, entry.rule_id, entry.title
        ));
    }

    Ok(vec![
        Artifact {
            rel_path: PathBuf::from("deny-set/lints.toml"),
            contents: table,
        },
        Artifact {
            rel_path: PathBuf::from("deny-set/clippy.toml"),
            contents: config,
        },
        Artifact {
            rel_path: PathBuf::from("deny-set/rulemap.tsv"),
            contents: map,
        },
    ])
}

pub fn oxlintrc_json(rules: &[Detector]) -> String {
    let mut out = String::from("{\n  \"plugins\": [\"typescript\"],\n  \"categories\": {\n");
    let categories: Vec<String> = OXLINT_CATEGORIES
        .iter()
        .map(|c| format!("    \"{c}\": \"off\""))
        .collect();
    out.push_str(&categories.join(",\n"));
    out.push_str("\n  },\n  \"rules\": {\n");
    let entries: Vec<String> = rules
        .iter()
        .map(|d| format!("    \"{}\": \"{}\"", d.name, d.level.name()))
        .collect();
    out.push_str(&entries.join(",\n"));
    out.push_str("\n  }\n}\n");
    out
}

fn rulemap(sha: &str, tool: &str, groups: &[(&str, &[Detector])]) -> String {
    let mut map = format!("# wieland-corpus: {sha}\n");
    map.push_str(&format!("# {tool}\tlevel\trule_id\ttitle\n"));
    for (prefix, detectors) in groups {
        for d in detectors.iter() {
            map.push_str(&format!(
                "{prefix}{}\t{}\t{}\t{}\n",
                d.name,
                d.level.name(),
                d.rule_id,
                d.title
            ));
        }
    }
    map
}

fn render_typescript(corpus: &Corpus, sha: &str) -> Vec<Artifact> {
    let rules = oxlint_rules(corpus);
    let flags = tsconfig_flags(corpus);
    vec![
        Artifact {
            rel_path: in_pack(Language::Typescript, "deny-set/oxlintrc.json"),
            contents: oxlintrc_json(&rules),
        },
        Artifact {
            rel_path: in_pack(Language::Typescript, "deny-set/rulemap.tsv"),
            contents: rulemap(
                sha,
                "detector",
                &[("oxlint::", &rules), ("tsconfig::", &flags)],
            ),
        },
    ]
}

pub const ERRCHECK_EXCLUDED: [&str; 1] = ["(io.ReadCloser).Close"];

pub fn golangci_yml(linters: &[Detector]) -> String {
    let mut out = String::from(
        "version: \"2\"\nrun:\n  relative-path-mode: wd\nissues:\n  max-issues-per-linter: 0\n  max-same-issues: 0\n  uniq-by-line: false\nlinters:\n  default: none\n  enable:\n",
    );
    for d in linters {
        out.push_str(&format!("    - {}\n", d.name));
    }
    if linters.iter().any(|d| d.name == "errcheck") {
        out.push_str("  settings:\n    errcheck:\n      exclude-functions:\n");
        for function in ERRCHECK_EXCLUDED {
            out.push_str(&format!("        - {function}\n"));
        }
    }
    out.push_str("formatters:\n  enable: []\n");
    out
}

fn render_go(corpus: &Corpus, sha: &str) -> Vec<Artifact> {
    let linters = golangci_linters(corpus);
    vec![
        Artifact {
            rel_path: in_pack(Language::Go, "deny-set/golangci.yml"),
            contents: golangci_yml(&linters),
        },
        Artifact {
            rel_path: in_pack(Language::Go, "deny-set/rulemap.tsv"),
            contents: rulemap(sha, "detector", &[("golangci::", &linters)]),
        },
    ]
}
